#!/usr/bin/env bash
# Capture the board facts needed to interpret a regression run.
#
# Usage:
#   scripts/board_info.sh [output.md]
#   BOARD=my-rk3588-host scripts/board_info.sh docs/board.md
set -euo pipefail

BOARD="${BOARD:-t6}"
OUTPUT="${1:-docs/board.md}"
TMP="$(mktemp "${TMPDIR:-/tmp}/rk-mpp-board.XXXXXX")"
trap 'rm -f "$TMP"' EXIT

remote() {
  ssh "$BOARD" "$1"
}

{
  printf '# Board: %s\n\n' "$BOARD"
  printf 'Generated by `scripts/board_info.sh`; rerun it after kernel or driver changes.\n\n'

  printf '## Identity\n\n```text\n'
  remote 'date -Is; uname -a; cat /etc/os-release'
  printf '```\n\n'

  printf '## Hardware\n\n```text\n'
  remote '
    test -r /proc/device-tree/model && tr -d "\0" < /proc/device-tree/model || true
    printf "\n"
    test -r /proc/device-tree/compatible && tr "\0" "\n" < /proc/device-tree/compatible || true
    grep -m1 -E "^(model name|Hardware|Processor)" /proc/cpuinfo || true
    printf "logical CPUs: "; nproc
    grep -m1 MemTotal /proc/meminfo || true
    printf "serial: "; if test -r /proc/device-tree/serial-number; then
      tr -d "\0" < /proc/device-tree/serial-number
    else
      printf "-"
    fi
    printf "\n"
  '
  printf '```\n\n'

  printf '## Kernel and command line\n\n```text\n'
  remote '
    printf "kernel: "; uname -r
    printf "cmdline: "; cat /proc/cmdline
    printf "governor: "; cat /sys/devices/system/cpu/cpu0/cpufreq/scaling_governor 2>/dev/null || printf "-\n"
    printf "thermal zones:\n"; for z in /sys/class/thermal/thermal_zone*; do
      test -e "$z/type" || continue
      temp="$(cat "$z/temp" 2>/dev/null || printf 0)"
      printf "  %s: %s = " "${z##*/}" "$(cat "$z/type")"
      awk -v value="$temp" "BEGIN { printf \"%.3f C\\n\", value / 1000 }"
    done
  '
  printf '```\n\n'

  printf '## MPP and DMA devices\n\n```text\n'
  remote '
    for p in /dev/mpp_service /dev/dma_heap/system /dev/dma_heap/system-uncached /dev/dma_heap/cma; do
      if test -e "$p"; then ls -l "$p"; else printf "missing %s\n" "$p"; fi
    done
    printf "mpp driver links:\n"
    ls /sys/bus/platform/drivers 2>/dev/null |
      grep -E "(^|_)(mpp|rkvdec|rkvenc|rga|iep|vpu|vepu|vdpu)" |
      sed "s/^/  /" || true
    find -L /sys/class/misc /sys/class/devfreq -maxdepth 2 -iname "*mpp*" -o -iname "*rkvdec*" -o -iname "*rkvenc*" 2>/dev/null |
      sort | sed "s/^/  /" | head -40
    printf "kernel modules:\n"
    grep -E "(^|_)(rkvdec|rkvenc|mpp|rga|iep|vpu|vepu|vdpu)" /proc/modules 2>/dev/null || printf "  none listed\n"
  '
  printf '```\n\n'

  printf '## MPP capability probe\n\n```text\n'
  remote '
    export PATH="$HOME/.cargo/bin:$PATH"
    cd "$HOME/rk-mpp-rs"
    printf "repo: "; git rev-parse --short HEAD
    cargo build --quiet --release >/dev/null 2>&1
    timeout 60 ./target/release/rk-mpp-rs probe 2>&1
  '
  printf '```\n'
} >"$TMP"

mv "$TMP" "$OUTPUT"
trap - EXIT
printf 'wrote %s\n' "$OUTPUT"
