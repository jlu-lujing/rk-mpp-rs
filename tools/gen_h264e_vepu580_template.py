#!/usr/bin/env python3
"""Generate the bootstrapping VEPU580 H.264 register template from an ioctl trace.

Usage:
    tools/gen_h264e_vepu580_template.py /tmp/mpp_trace.log \
        src/hal/h264e_vepu580_template.rs

The template is deliberately an integration checkpoint, not a substitute for
the parameterized VEPU580 register generator. Address words are patched by the
Rust caller and tests compare every non-address word against the board dump.
"""

from __future__ import annotations

import argparse
from pathlib import Path

SECTIONS = {
    0: ("CTL", 24),
    640: ("BASE", 94),
    4096: ("RCKLUT", 57),
    5888: ("PARAM", 180),
    8192: ("RDO", 122),
    8704: ("SCL", 679),
    12288: ("OSD", 288),
}


def extract(path: Path) -> dict[str, list[int]]:
    lines = path.read_text(errors="replace").splitlines()
    result: dict[str, list[int]] = {}
    for index, line in enumerate(lines):
        marker = "mpp_trace before cmd=200"
        if marker not in line or "size=" not in line:
            continue
        fields = dict(
            item.split("=", 1) for item in line.split() if "=" in item and item.split("=", 1)[0] in {"size", "offset"}
        )
        offset = int(fields["offset"], 0)
        if offset not in SECTIONS:
            continue
        name, expected_words = SECTIONS[offset]
        word_line = lines[index + 1]
        if "mpp_trace write words=" not in word_line:
            raise RuntimeError(f"missing words after {line}")
        words = [int(value, 16) for value in word_line.split()[3:]]
        if len(words) != expected_words:
            raise RuntimeError(f"{name}: got {len(words)} words, expected {expected_words}")
        result[name] = words
    missing = set(name for name, _ in SECTIONS.values()) - result.keys()
    if missing:
        raise RuntimeError(f"missing sections: {sorted(missing)}")
    return result


def render(sections: dict[str, list[int]]) -> str:
    out = [
        "// @generated by tools/gen_h264e_vepu580_template.py from the installed",
        "// RK3588 librockchip_mpp trace for 320x240 Baseline/FIXQP26/GOP1.",
        "",
    ]
    for name, words in sections.items():
        out.append(f"pub const {name}_WORDS: [u32; {len(words)}] = [")
        for start in range(0, len(words), 8):
            chunk = ", ".join(f"0x{word:08x}" for word in words[start : start + 8])
            out.append(f"    {chunk},")
        out.extend(["];", ""])
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("trace", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(render(extract(args.trace)))


if __name__ == "__main__":
    main()
