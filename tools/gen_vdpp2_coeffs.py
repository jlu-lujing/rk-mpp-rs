#!/usr/bin/env python3
"""Generate the VDPP2 ZME coefficient tables from vdpp_common.c."""

from __future__ import annotations

import argparse
import re
from pathlib import Path


def array_body(source: str, name: str) -> str:
    match = re.search(
        rf"{re.escape(name)}\s*\[[^=]+\]\s*=\s*\{{(.*?)\n\}};",
        source,
        re.S,
    )
    if not match:
        raise SystemExit(f"missing {name}")
    return match.group(1)


def parse_i16_table(source: str, name: str) -> list[list[list[int]]]:
    body = array_body(source, name)
    rows = []
    for outer in re.findall(r"\{((?:\s*\{[^{}]+\}\s*,?)+)\s*\}", body):
        table = []
        for row in re.findall(r"\{([^{}]+)\}", outer):
            values = [int(value) for value in re.findall(r"-?\d+", row)]
            if len(values) != 8:
                raise SystemExit(f"{name}: expected 8 taps, got {values}")
            table.append(values)
        if len(table) != 17:
            raise SystemExit(f"{name}: expected 17 phases, got {len(table)}")
        rows.append(table)
    if len(rows) != 11:
        raise SystemExit(f"{name}: expected 11 scale rows, got {len(rows)}")
    return rows


def emit_table(name: str, table: list[list[list[int]]]) -> str:
    lines = [f"pub const {name}: [[[i16; 8]; 17]; 11] = ["]
    for scale in table:
        lines.append("    [")
        for phase in scale:
            values = ", ".join(str(value) for value in phase)
            lines.append(f"        [{values}],")
        lines.append("    ],")
    lines.append("];")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()

    source = args.source.read_text()
    tap8 = parse_i16_table(source, "g_zme_tap8_coeff")
    tap6 = parse_i16_table(source, "g_zme_tap6_coeff")
    args.output.write_text(
        "// Generated by tools/gen_vdpp2_coeffs.py from MPP vdpp_common.c.\n"
        "// Do not edit by hand.\n\n"
        + emit_table("TAP8", tap8)
        + "\n\n"
        + emit_table("TAP6", tap6)
        + "\n"
    )


if __name__ == "__main__":
    main()
