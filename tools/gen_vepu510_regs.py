#!/usr/bin/env python3
"""Generate the RK3576 VEPU510 H.264 register field map.

The parser is shared with `gen_vepu580_regs.py`: the two register maps use the
same anonymous-bitfield declaration convention, where fields are allocated from
the low bit in declaration order. Section ranges and word counts come from
`vepu510_common.h` and are cross-checked against an lf1 ioctl trace.
"""

from pathlib import Path

import gen_vepu580_regs as base

ROOT = Path(__file__).resolve().parents[2]
COMMON = ROOT / "refs/mpp/mpp/hal/rkenc/common/vepu510_common.h"
H264E = ROOT / "refs/mpp/mpp/hal/rkenc/h264e/hal_h264e_vepu510_reg.h"

STRUCTS = [
    (COMMON, "Vepu510ControlCfg", "CTL", 0, 24),
    (COMMON, "Vepu510FrmCommon", "FRAME", 156, 98),
    (H264E, "H264eVepu510Frame", "H264", 156, 98),
    (COMMON, "Vepu510RcRoi", "RC", 1024, 68),
    (H264E, "H264eVepu510Param", "PARAM", 1472, 180),
    (COMMON, "Vepu510WgtCommon", "PARAM", 1496, 180),
    (H264E, "H264eVepu510SqiCfg", "SQI", 2048, 47),
    (COMMON, "Vepu510SclCfg", "SCL", 2176, 226),
    (COMMON, "Vepu510Status", "STATUS", 4096, 148),
]

SECTIONS = [
    ("ctl", 0, 24),
    ("frame", 156, 98),
    ("rc", 1024, 68),
    ("param", 1472, 180),
    ("sqi", 2048, 47),
    ("scl", 2176, 226),
]
STATUS_OFFSET = 4096
STATUS_WORDS = 148


def main() -> int:
    sections = ", ".join(
        '("%s", %d, %d)' % (name, word, count)
        for name, word, count in SECTIONS
    )
    out = [
        "// @generated by tools/gen_vepu510_regs.py from",
        "// refs/mpp/mpp/hal/rkenc/common/vepu510_common.h and",
        "// refs/mpp/mpp/hal/rkenc/h264e/hal_h264e_vepu510_reg.h.",
        "// Do not edit by hand.",
        "",
        "//! VEPU510 register field positions for the RK3576 H.264 encoder.",
        "",
        "/// A register array addressed as whole words.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct Array {",
        "    pub word: usize,",
        "    pub count: usize,",
        "    pub elem_bytes: usize,",
        "    pub words: usize,",
        "    pub name: &'static str,",
        "}",
        "",
        "/// One named register field.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct Field {",
        "    /// Absolute word index in the VEPU510 register window.",
        "    pub word: usize,",
        "    pub shift: u32,",
        "    pub width: u32,",
        "    pub name: &'static str,",
        "}",
        "",
        "/// Written sections in ioctl order.",
        f"pub const SECTIONS: [(&str, usize, usize); {len(SECTIONS)}] = [{sections}];",
        f"pub const STATUS_OFFSET: usize = {STATUS_OFFSET};",
        f"pub const STATUS_WORDS: usize = {STATUS_WORDS};",
        "",
    ]

    emitted = 0
    seen: set[str] = set()
    for header, struct, prefix, first_word, words in STRUCTS:
        out.append(f"// {struct} ({header.name}) at absolute word {first_word}.")
        body = base.struct_body(header.read_text(), struct)
        for word, group, fields, consumed in base.members(body, first_word):
            if not group.startswith("reserved") and word + consumed > first_word + words:
                raise SystemExit(
                    f"{struct}.{group}: word {word} is outside {first_word}+{words}"
                )
            if fields and fields[0][0] == "@array":
                _, array_words, elem_bytes, count = fields[0]
                const = f"{prefix}_{group.upper()}"
                if const in seen:
                    continue
                seen.add(const)
                out.append(
                    f"pub const {const}: Array = Array {{ word: {word}, "
                    f"count: {count}, elem_bytes: {elem_bytes}, words: {array_words}, "
                    f'name: "{prefix}.{group}" }};'
                )
                emitted += 1
                continue

            if word is None:
                raise SystemExit(f"{struct}.{group}: no register word")
            named = [name for name, _ in fields if name]
            total = sum(bits for _, bits in fields)
            if len(named) > 1 and total != 32:
                raise SystemExit(
                    f"{struct}.{group}: fields add to {total} bits, not 32"
                )
            shift = 0
            for name, width in fields:
                if not name or name.startswith("reserved"):
                    shift += width
                    continue
                const = f"{prefix}_{group}_{name}".upper()
                if const in seen:
                    shift += width
                    continue
                seen.add(const)
                out.append(
                    f"pub const {const}: Field = Field {{ word: {word}, shift: {shift}, "
                    f'width: {width}, name: "{prefix}.{group}.{name}" }};'
                )
                emitted += 1
                shift += width
        out.append("")

    out.append(f"// {emitted} fields in total.")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
