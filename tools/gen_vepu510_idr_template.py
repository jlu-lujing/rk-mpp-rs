#!/usr/bin/env python3
"""Convert an mpp_ioctl_trace VEPU510 fixed-QP IDR job into Rust arrays.

Input is the stderr log from:

    LD_PRELOAD=/tmp/mpp_trace_rk3576.so h264e_probe ... 1 0 26

The output is a raw first-IDR template. DMA fds, dimensions, QP and syntax are
expected to be overwritten by the builder that consumes these arrays.
"""

import re
import sys
from pathlib import Path

EXPECTED_WRITES = [
    ("CTL", 24, 0, 24),
    ("FRAME", 156, 624, 98),
    ("RC", 1024, 4096, 68),
    ("PARAM", 1472, 5888, 180),
    ("SQI", 2048, 8192, 47),
    ("SCL", 2176, 8704, 226),
]
STATUS = ("STATUS", 4096, 16384, 148)


def parse_trace(text: str):
    lines = text.splitlines()
    writes = []
    statuses = []
    for index, line in enumerate(lines):
        match = re.search(r"after cmd=200 .*size=(\d+) offset=(\d+)", line)
        if match:
            if index + 1 >= len(lines):
                raise SystemExit("write header has no following words")
            words_match = re.search(
                r"mpp_trace write words=(\d+) (.*)", lines[index + 1]
            )
            if not words_match:
                raise SystemExit(f"no write words after line {index + 1}")
            size = int(match.group(1))
            offset = int(match.group(2))
            words = [int(word, 16) for word in words_match.group(2).split()]
            if size != len(words) * 4 or offset % 4:
                raise SystemExit(f"malformed write at byte offset {offset}")
            writes.append((offset, words))

        if "@16384" in line and "read_complete[" in line:
            words_match = re.search(r"words=(\d+) (.*)", line)
            if not words_match:
                raise SystemExit("malformed STATUS read")
            statuses.append(
                [int(word, 16) for word in words_match.group(2).split()]
            )

    if not writes or len(writes) % len(EXPECTED_WRITES):
        raise SystemExit(f"expected whole jobs, found {len(writes)} writes")
    jobs = []
    for start in range(0, len(writes), len(EXPECTED_WRITES)):
        job = writes[start : start + len(EXPECTED_WRITES)]
        for (name, _, expected_offset, expected_count), (offset, words) in zip(
            EXPECTED_WRITES, job
        ):
            if offset != expected_offset or len(words) != expected_count:
                raise SystemExit(
                    f"{name}: got byte offset {offset}, {len(words)} words; "
                    f"expected {expected_offset}, {expected_count}"
                )
        jobs.append([words for _, words in job])
    if len(statuses) < len(jobs) or any(len(status) != STATUS[3] for status in statuses):
        raise SystemExit(f"expected {STATUS[3]} STATUS words")
    return jobs, statuses


def array(name: str, words) -> list[str]:
    out = [f"pub const {name}: [u32; {len(words)}] = ["]
    for start in range(0, len(words), 8):
        row = ", ".join(f"0x{word:08x}" for word in words[start : start + 8])
        out.append(f"    {row},")
    out.append("];")
    return out


def main() -> int:
    path = Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/h264e_fixqp_trace.log")
    job_index = int(sys.argv[2]) if len(sys.argv) > 2 else 0
    jobs, statuses = parse_trace(path.read_text())
    if job_index >= len(jobs):
        raise SystemExit(f"job {job_index} is outside {len(jobs)} captured jobs")
    writes = jobs[job_index]
    status = statuses[job_index]
    out = [
        "// @generated by tools/gen_vepu510_idr_template.py from",
        f"// {path}.",
        f"// Captured from RK3576 fixed-QP 320x240 job {job_index}.",
        "// Raw addresses are placeholders for a builder to overwrite.",
        "",
    ]
    for (name, _, _, _), words in zip(EXPECTED_WRITES, writes):
        out.extend(array(name, words))
        out.append("")
    out.extend(array(STATUS[0], status))
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
