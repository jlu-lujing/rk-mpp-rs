#!/usr/bin/env python3
"""Generate the VEPU580 H.265 register template from an ioctl trace.

    tools/gen_h265e_vepu580_template.py /tmp/h265-trace.txt \
        src/hal/h265e_vepu580_template.rs

The trace is one fixed-QP IDR from the vintage C encoder on t6:

    sudo env LD_LIBRARY_PATH=/tmp/mpp-old/build/mpp LD_PRELOAD=/tmp/mpp_trace.so \
      mpi_enc_test -i probe-320x240.nv12 -o out.265 -w 320 -h 240 \
      -t 16777220 -f 0 -n 1 -rc 2 -qc 26:26:26:26:26 -v q

Like the H.264 template, this is an integration checkpoint: the image starts
from these words and `hal::h265e` derives the geometry, QP and syntax fields on
top. The tuning windows (wgt, rdo) and the byte tables inside rc-klut have no
public formula in the C - they are constants the HAL writes - so they are
captured here rather than invented. Address words stay as traced; the submit
path will patch them, and until then the diff tool reports them separately.
"""

from __future__ import annotations

import argparse
from pathlib import Path

SECTIONS = {
    0: ("CTL", 24),
    640: ("BASE", 94),
    4096: ("RC_KLUT", 57),
    5888: ("WGT", 374),
    8192: ("RDO", 807),
    12288: ("OSD", 288),
}


def extract(path: Path) -> dict[str, list[int]]:
    lines = path.read_text(errors="replace").splitlines()
    result: dict[str, list[int]] = {}
    for index, line in enumerate(lines):
        if "mpp_trace before cmd=200" not in line or "size=" not in line:
            continue
        fields = dict(
            item.split("=", 1)
            for item in line.split()
            if "=" in item and item.split("=", 1)[0] in {"size", "offset"}
        )
        offset = int(fields["offset"], 0)
        if offset not in SECTIONS:
            raise RuntimeError(f"unexpected register window at offset {offset}")
        name, expected = SECTIONS[offset]
        words_line = lines[index + 1]
        if "mpp_trace write words=" not in words_line:
            raise RuntimeError(f"missing words after {line}")
        words = [int(value, 16) for value in words_line.split()[3:]]
        if len(words) != expected:
            raise RuntimeError(f"{name}: {len(words)} words, expected {expected}")
        result[name] = words
    missing = {name for name, _ in SECTIONS.values()} - set(result)
    if missing:
        raise RuntimeError(f"missing sections: {sorted(missing)}")
    return result


def render(sections: dict[str, list[int]]) -> str:
    out = [
        "// @generated by tools/gen_h265e_vepu580_template.py from the t6",
        "// librockchip_mpp trace for a 320x240 fixed-QP 26 single IDR",
        "// (`mpi_enc_test -t 16777220 -rc 2 -n 1`). Six windows: H.265 has no SCL.",
        "",
    ]
    for name, _ in SECTIONS.values():
        words = sections[name]
        out.append(f"pub const {name}_WORDS: [u32; {len(words)}] = [")
        for start in range(0, len(words), 8):
            chunk = ", ".join(f"0x{word:08x}" for word in words[start : start + 8])
            out.append(f"    {chunk},")
        out.extend(["];", ""])
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("trace", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(render(extract(args.trace)))


if __name__ == "__main__":
    main()
