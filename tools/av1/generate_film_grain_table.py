#!/usr/bin/env python3
"""Import the AV1 film-grain Gaussian sequence from the vendored MPP source."""

from pathlib import Path
import re


PROJECT = Path(__file__).resolve().parents[2]
WORKSPACE = PROJECT.parent
SOURCE = WORKSPACE / "refs/mpp/mpp/hal/common/av1/film_grain_noise_table.c"
OUTPUT = PROJECT / "src/hal/av1_film_grain_table.rs"


def main() -> None:
    source = SOURCE.read_text()
    match = re.search(
        r"gaussian_sequence\s*\[\s*2048\s*\]\s*=\s*\{(.*?)\};",
        source,
        re.DOTALL,
    )
    if match is None:
        raise SystemExit("gaussian_sequence initializer not found")

    values = [int(value) for value in re.findall(r"-?\d+", match.group(1))]
    if len(values) != 2048:
        raise SystemExit(f"expected 2048 Gaussian values, found {len(values)}")
    if any(value < -32768 or value > 32767 for value in values):
        raise SystemExit("a Gaussian value does not fit in i16")

    lines = [
        "// Generated by tools/av1/generate_film_grain_table.py.",
        "// Source: refs/mpp/mpp/hal/common/av1/film_grain_noise_table.c.",
        "",
        "pub const GAUSSIAN_SEQUENCE: [i16; 2048] = [",
    ]
    for start in range(0, len(values), 8):
        row = ", ".join(str(value) for value in values[start : start + 8])
        lines.append(f"    {row},")
    lines.extend(["];", ""])
    OUTPUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
