#!/usr/bin/env python3
"""Generate the rkvdec H.264 register map from hal_h264d_rkv_reg.h.

The C header is a sequence of `struct { RK_U32 field : width; ... } swNN;`
blocks packed LSB-first into one 32-bit word. We emit a Rust `Field` constant
per bitfield plus array accessors, so the HAL can write registers by name with
no runtime lookup.
"""
import re
import sys

def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    text = re.sub(r'//[^\n]*', '', text)
    return text

def parse(path):
    text = strip_comments(open(path).read())
    body = text[text.index('typedef struct h264d_rkv_regs_t {'):]
    words = []  # (kind, name, count, fields[(name,width)])
    i = 0
    for m in re.finditer(r'\}\s*(\w+)(?:\[(\d+)\])?\s*;', body):
        name, count = m.group(1), int(m.group(2)) if m.group(2) else 1
        start = body.rfind('{', 0, m.start())
        block = body[start:m.start()]
        arr = re.search(r'RK_U32\s+(\w+)\s*\[(\d+)\]\s*;', block)
        if arr:
            # unnamed tail array, e.g. `RK_U32 reverse[2];` in the closing block
            words.append((arr.group(1), int(arr.group(2)), []))
            continue
        fields = []
        for fm in re.finditer(r'RK_U32\s+(\w+)\s*(?::\s*(\d+))?\s*;', block):
            fields.append((fm.group(1), int(fm.group(2)) if fm.group(2) else 32))
        words.append((name, count, fields))
    return words

def main():
    src = sys.argv[1]
    out = sys.argv[2]
    words = parse(src)
    lines = []
    idx = 0
    entries = []
    for name, count, fields in words:
        if fields and len(fields) == 1 and not re.match(r'^sw\d', name):
            # unnamed trailing array, e.g. reverse[2]
            base = idx
            idx += count
            continue
        if count == 1:
            base = idx
            total = sum(w for _, w in fields)
            assert total <= 32, f"{name}: {total} bits"
            lsb = 0
            for fname, width in fields:
                entries.append((name, None, fname, base, lsb, width))
                lsb += width
            idx += 1
        else:
            base = idx
            total = sum(w for _, w in fields)
            assert total <= 32, f"{name}: {total} bits"
            lsb = 0
            for fname, width in fields:
                entries.append((name, count, fname, base, lsb, width))
                lsb += width
            idx += count
    n_words = idx  # includes the trailing reverse[2]

    out_lines = []
    out_lines.append('//! rkvdec H.264 register file (80 words).')
    out_lines.append('//!')
    out_lines.append('//! Generated by `tools/gen_h264_regs.py` from the official MPP')
    out_lines.append('//! `hal/rkdec/h264d/hal_h264d_rkv_reg.h`. Do not edit by hand.')
    out_lines.append('')
    out_lines.append(f'pub const N_WORDS: usize = {n_words};')
    out_lines.append('')
    out_lines.append('/// One bitfield inside the register file.')
    out_lines.append('#[derive(Debug, Clone, Copy, PartialEq, Eq)]')
    out_lines.append('pub struct Field {')
    out_lines.append('    pub word: usize,')
    out_lines.append('    pub lsb: u8,')
    out_lines.append('    pub width: u8,')
    out_lines.append('}')
    out_lines.append('')
    out_lines.append('pub struct Regs {')
    out_lines.append('    pub w: [u32; N_WORDS],')
    out_lines.append('}')
    out_lines.append('')
    out_lines.append('impl Default for Regs {')
    out_lines.append('    fn default() -> Self {')
    out_lines.append('        Regs { w: [0; N_WORDS] }')
    out_lines.append('    }')
    out_lines.append('}')
    out_lines.append('')
    out_lines.append('impl Regs {')
    out_lines.append('    pub fn new() -> Self {')
    out_lines.append('        Self::default()')
    out_lines.append('    }')
    out_lines.append('')
    out_lines.append('    #[inline]')
    out_lines.append('    pub fn set(&mut self, f: Field, v: u32) -> &mut Self {')
    out_lines.append('        let mask = if f.width >= 32 { u32::MAX } else { (1u32 << f.width) - 1 };')
    out_lines.append('        let shift = f.lsb as u32;')
    out_lines.append('        self.w[f.word] = (self.w[f.word] & !(mask << shift)) | ((v & mask) << shift);')
    out_lines.append('        self')
    out_lines.append('    }')
    out_lines.append('')
    out_lines.append('    #[inline]')
    out_lines.append('    pub fn get(&self, f: Field) -> u32 {')
    out_lines.append('        let mask = if f.width >= 32 { u32::MAX } else { (1u32 << f.width) - 1 };')
    out_lines.append('        (self.w[f.word] >> f.lsb) & mask')
    out_lines.append('    }')
    out_lines.append('}')

    # group entries per word
    by_word = {}
    for struct, count, fname, base, lsb, width in entries:
        by_word.setdefault((struct, count, base), []).append((fname, lsb, width))

    for (struct, count, base), flds in by_word.items():
        mod = re.sub(r'\W', '_', struct)
        out_lines.append('')
        if count is None:
            out_lines.append(f'/// `{struct}` (word {base})')
            out_lines.append(f'pub mod {mod} {{')
            out_lines.append('    use super::Field;')
            out_lines.append(f'    pub const WORD: usize = {base};')
            for fname, lsb, width in flds:
                out_lines.append(f'    pub const {fname.upper()}: Field = Field {{ word: WORD, lsb: {lsb}, width: {width} }};')
            out_lines.append('}')
        else:
            out_lines.append(f'/// `{struct}[{count}]` (words {base}..{base + count - 1})')
            out_lines.append(f'pub mod {mod} {{')
            out_lines.append('    use super::Field;')
            out_lines.append(f'    pub const BASE: usize = {base};')
            out_lines.append(f'    pub const COUNT: usize = {count};')
            out_lines.append('    #[inline]')
            out_lines.append('    pub fn word(i: usize) -> usize {')
            out_lines.append(f'        assert!(i < COUNT, "index {{}} out of range for {struct}", i);')
            out_lines.append('        BASE + i')
            out_lines.append('    }')
            for fname, lsb, width in flds:
                out_lines.append(f'    pub const {fname.upper()}: (u8, u8) = ({lsb}, {width});')
                out_lines.append('    #[inline]')
                out_lines.append(f'    pub fn {fname}(i: usize) -> Field {{')
                out_lines.append(f'        Field {{ word: word(i), lsb: {lsb}, width: {width} }}')
                out_lines.append('    }')
            out_lines.append('}')

    out_lines.append('')
    out_lines.append('#[cfg(test)]')
    out_lines.append('mod tests {')
    out_lines.append('    use super::*;')
    out_lines.append('')
    out_lines.append('    #[test]')
    out_lines.append('    fn packs_lsb_first() {')
    out_lines.append('        let mut r = Regs::new();')
    out_lines.append('        r.set(sw02::IN_ENDIAN, 1)')
    out_lines.append('            .set(sw02::STREAM_LASTPACKET, 1)')
    out_lines.append('            .set(sw02::DEC_MODE, 3);')
    out_lines.append('        assert_eq!(r.get(sw02::IN_ENDIAN), 1);')
    out_lines.append('        assert_eq!(r.get(sw02::DEC_MODE), 3);')
    out_lines.append('        assert_eq!(r.w[sw02::WORD] & 0x3, 0b01);')
    out_lines.append('    }')
    out_lines.append('')
    out_lines.append('    #[test]')
    out_lines.append('    fn array_words_are_distinct() {')
    out_lines.append('        assert_eq!(sw10_24::word(0), 10);')
    out_lines.append('        assert_eq!(sw10_24::word(14), 24);')
    out_lines.append('        assert_eq!(sw25_39::word(0), 25);')
    out_lines.append('        assert_eq!(sw49_63::word(14), 63);')
    out_lines.append('    }')
    out_lines.append('}')
    open(out, 'w').write('\n'.join(out_lines) + '\n')
    print(f"{len(entries)} fields, {n_words} words -> {out}")

if __name__ == '__main__':
    main()
