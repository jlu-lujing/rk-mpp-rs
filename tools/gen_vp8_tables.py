#!/usr/bin/env python3
"""Generate the VP8 probability tables used by the vdpu2 decode path.

Source: refs/mpp/mpp/codec/dec/vp8/vp8d_data.h. Each table is a `static const
RK_U8 name[d0][d1]... = { ... };` initializer, so the brace nesting already
carries the shape and the only work is to rename the identifiers to the Rust
naming convention and re-flow the literals.

Run from the crate root:

    python3 tools/gen_vp8_tables.py > src/codec/vp8/tables.rs
"""
import re
import sys
from pathlib import Path

SOURCE = Path("refs/mpp/mpp/codec/dec/vp8/vp8d_data.h")

# C name -> (Rust name, doc comment)
TABLES = {
    "MvUpdateProbs": (
        "MV_UPDATE_PROBS",
        "`MvUpdateProbs`: the tree probabilities `vp8hwdDecodeBool` walks when a "
        "picture refreshes the motion-vector probabilities.",
    ),
    "Vp8DefaultMvProbs": (
        "VP8_DEFAULT_MV_PROBS",
        "`Vp8DefaultMvProbs`: the motion-vector probabilities a key frame starts from.",
    ),
    "CoeffUpdateProbs": (
        "COEFF_UPDATE_PROBS",
        "`CoeffUpdateProbs`: the tree probabilities of the coefficient-probability "
        "update loop itself, in token-tree / class / context / value order.",
    ),
    "DefaultCoeffProbs": (
        "DEFAULT_COEFF_PROBS",
        "`DefaultCoeffProbs`: the coefficient probabilities a key frame starts from.",
    ),
}

CONSTANTS = {
    "VP7_MV_PROBS_PER_COMPONENT": 17,
    "VP8_MV_PROBS_PER_COMPONENT": 19,
}


def balanced_braces(text: str, start: int) -> str:
    """The text between one `{` and its matching `}`, with inner braces kept out."""
    depth = 0
    for index in range(start, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1:index]
    raise SystemExit("unterminated initializer")


def wrapped(sentence, width=76):
    """Break a doc sentence so the generated file stays inside the line budget."""
    words, lines, current = sentence.split(), [], ""
    for word in words:
        if current and len(current) + len(word) + 1 > width:
            lines.append(current)
            current = word
        else:
            current = f"{current} {word}".strip()
    if current:
        lines.append(current)
    return lines


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def parse_table(text: str, name: str):
    """Return (dims, rows) for one `static const RK_U8 name[...] = {...};`."""
    pattern = (
        r"static\s+const\s+RK_U8\s+"
        + name
        + r"\s*((?:\[[^\]]*\])+)\s*="
    )
    match = re.search(pattern, text, re.S)
    if not match:
        raise SystemExit(f"{name}: not found in the C source")
    dims = []
    for token in re.findall(r"\[([^\]]+)\]", match.group(1)):
        token = token.strip()
        for constant, value in CONSTANTS.items():
            token = token.replace(constant, str(value))
        if not token.isdigit():
            raise SystemExit(f"{name}: cannot resolve dimension {token!r}")
        dims.append(int(token))
    body = balanced_braces(text, text.index("{", match.end() - 1))
    values = []
    for token in body.translate(str.maketrans("{},", "   ")).split():
        if not re.fullmatch(r"(?:0[xX][0-9a-fA-F]+|[0-9]+)", token):
            raise SystemExit(f"{name}: unexpected token {token!r}")
        values.append(int(token, 0))
    expected = 1
    for dim in dims:
        expected *= dim
    if len(values) != expected:
        raise SystemExit(f"{name}: {len(values)} values for shape {dims}")
    return dims, values


def nest(dims, values) -> list:
    """Fold the flat value list into Python lists shaped like the C array."""
    if len(dims) == 1:
        return values
    width = len(values) // dims[0]
    return [nest(dims[1:], values[i * width:(i + 1) * width]) for i in range(dims[0])]


def emit(value, indent: int) -> str:
    pad = "    " * indent
    if isinstance(value, list):
        rows = ", ".join(emit(item, indent + 1) for item in value)
        return f"[{rows}]"
    return f"{value}"


def rust_type(dims) -> str:
    out = "u8"
    for dim in reversed(dims):
        out = f"[{out}; {dim}]"
    return out


def main() -> int:
    text = strip_comments(SOURCE.read_text())
    print("// @generated by tools/gen_vp8_tables.py from\n"
          "// refs/mpp/mpp/codec/dec/vp8/vp8d_data.h. Do not edit by hand.\n")
    print("//! Probability tables of `mpp/codec/dec/vp8/vp8d_data.h`, kept in the C\n"
          "//! declaration order so `vp8hwdDecodeCoeffUpdate` and the probe-table writer\n"
          "//! can index them the same way the C decoder does.\n")
    for cname, (rname, doc) in TABLES.items():
        dims, values = parse_table(text, cname)
        for line in wrapped(doc):
            print(f"/// {line}")
        shape = rust_type(dims)
        if len(dims) == 1:
            rows = ", ".join(str(v) for v in values)
            print(f"pub const {rname}: {shape} = [{rows}];\n")
            continue
        print(f"pub const {rname}: {shape} = " + emit(nest(dims, values), 0) + ";\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
